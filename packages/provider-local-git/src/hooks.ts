/**
 * Server-side push guard installed in every repository the provider owns.
 *
 * The same POSIX `sh` script is installed as `pre-receive` (early, readable refusal) and as
 * `reference-transaction` (runs in the `prepared` state while git holds the ref locks, so a push
 * that passed `pre-receive` before a freeze is still refused if it commits after the freeze
 * marker exists). The repository's own config sets `core.hooksPath` to the guard directory, so a
 * pusher's global config cannot point hooks elsewhere (repo-local config wins over global, and
 * git drops `GIT_CONFIG_PARAMETERS`/`GIT_CONFIG_COUNT` for local transports).
 *
 * The credential reaches the hook as `COMMONFORGE_TOKEN` in the receive-pack environment: over
 * `file://` the pusher sets it; over smart HTTP the authenticating front sets it from the
 * request's bearer token (see `LocalGitProvider.authorizeGitRequest`). Only the git object-id
 * digest of a token (`git hash-object --stdin`) is stored, never the secret.
 *
 * ADVISORY over `file://`: the pusher spawns receive-pack itself and controls its command line
 * (`--receive-pack='git -c core.hooksPath=/dev/null receive-pack'` skips this guard) and its
 * `PATH` (a fake `date` or `git`). The guard is a security boundary only behind the HTTP front,
 * where agents cannot reach the repository directory. It also fires for local ref transactions,
 * so operator maintenance must go through `LocalGitProvider.maintain()` or use
 * `-c core.hooksPath=<empty dir>`.
 *
 * - canonical: accepts only a digest listed in `commonforge/service/` (the runner's credential).
 * - task: refuses everything once `commonforge/frozen` exists; otherwise needs a digest listed in
 *   `commonforge/tokens/` whose record says `write` and whose expiry (epoch seconds) is in the future.
 */

export type GuardRole = 'canonical' | 'task';

/** Prefix of every credential secret this provider mints (helps redaction and the guard). */
export const TOKEN_PREFIX = 'cflg_';

/** Directory inside a bare repository holding the provider's state for that repository. */
export const STATE_DIR = 'commonforge';
export const HOOKS_DIR = `${STATE_DIR}/hooks`;
export const TOKENS_DIR = `${STATE_DIR}/tokens`;
export const SERVICE_DIR = `${STATE_DIR}/service`;
export const FROZEN_MARKER = `${STATE_DIR}/frozen`;

export const GUARDED_HOOKS = ['pre-receive', 'reference-transaction'] as const;

export function guardScript(role: GuardRole): string {
  return `#!/bin/sh
# Generated by @commonforge-org/provider-local-git. Do not edit: the provider rewrites it.
# Push guard for a ${role} repository.
ROLE=${role}
gd="\${GIT_DIR:-.}"
state="$gd/${STATE_DIR}"
case "$(basename "$0")" in
  reference-transaction)
    cat >/dev/null
    [ "$1" = prepared ] || exit 0
    ;;
  *) cat >/dev/null ;;
esac
refuse() { echo "commonforge: push refused: $*" >&2; exit 1; }
t="\${COMMONFORGE_TOKEN:-}"
[ -n "$t" ] || refuse "no CommonForge credential"
case "$t" in ${TOKEN_PREFIX}*) ;; *) refuse "malformed credential" ;; esac
case "$t" in *[!A-Za-z0-9_]*) refuse "malformed credential" ;; esac
d=$(printf '%s' "$t" | git hash-object --stdin) || refuse "cannot check credential"
if [ "$ROLE" = canonical ]; then
  [ -f "$state/service/$d" ] || refuse "canonical accepts only the service credential"
  exit 0
fi
[ -e "$state/frozen" ] && refuse "workspace is frozen"
f="$state/tokens/$d"
[ -f "$f" ] || refuse "credential is not valid for this workspace"
read -r scope expires _rest < "$f" || refuse "credential record unreadable"
[ "$scope" = write ] || refuse "read-only credential"
case "$expires" in ''|*[!0-9]*) refuse "credential record malformed" ;; esac
now=$(date +%s)
[ "$now" -lt "$expires" ] || refuse "credential expired"
exit 0
`;
}
