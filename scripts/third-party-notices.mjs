#!/usr/bin/env node
// Regenerate THIRD_PARTY_NOTICES.md from the lockfile's production dependencies.
//
//   node scripts/third-party-notices.mjs            # writes THIRD_PARTY_NOTICES.md at the repo root
//   node scripts/third-party-notices.mjs --check    # exits 1 if the file is out of date
//
// Source of truth: `pnpm licenses list --prod --json` (runtime dependencies of every workspace
// package, resolved from pnpm-lock.yaml and the installed node_modules; run `pnpm install` first).
// Each package's own licence file is copied in verbatim. Assets that are not npm dependencies
// (the self-hosted IBM Plex fonts) and the runner container image are listed by hand below.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "THIRD_PARTY_NOTICES.md");
const json = JSON.parse(execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));

const pkgs = [];
for (const [license, list] of Object.entries(json)) {
  for (const p of list) pkgs.push({ ...p, license });
}
pkgs.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

function licenseText(paths) {
  for (const dir of paths ?? []) {
    if (!existsSync(dir)) continue;
    const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(n));
    if (f) return readFileSync(join(dir, f), "utf8").trim();
  }
  return null;
}

const lines = [];
lines.push("# Third-party notices");
lines.push("");
lines.push("CommonForge is MIT-licensed (see `LICENSE`). It ships or deploys the third-party software below.");
lines.push("");
lines.push("Generated by `node scripts/third-party-notices.mjs` from `pnpm licenses list --prod --json`");
lines.push("(the runtime dependencies of every workspace package in `pnpm-lock.yaml`; development-only");
lines.push("tooling such as TypeScript, Vitest, Vite, Wrangler and Playwright is not redistributed and is");
lines.push("not listed). Do not edit by hand: rerun the script after a dependency change.");
lines.push("");
lines.push("## npm runtime dependencies");
lines.push("");
lines.push("| Package | Version | Licence | Homepage |");
lines.push("|---|---|---|---|");
for (const p of pkgs) lines.push(`| ${p.name} | ${p.versions.join(", ")} | ${p.license} | ${p.homepage ?? ""} |`);
lines.push("");
lines.push("## Bundled assets");
lines.push("");
lines.push("| Asset | Where | Licence |");
lines.push("|---|---|---|");
lines.push("| IBM Plex Sans and IBM Plex Mono (latin subsets, WOFF2) | `apps/web/public/fonts/` | SIL Open Font License 1.1, full text in `apps/web/public/fonts/OFL.txt` |");
lines.push("");
lines.push("## Runner container image");
lines.push("");
lines.push("Built at deploy time from `apps/runner/Dockerfile` and not stored in this repository. Its base");
lines.push("image and tools keep their own licences: `node:22-trixie-slim` (Node.js: MIT; Debian packages:");
lines.push("their respective licences), `git` (GPL-2.0, run as a separate program), `pnpm` (MIT), `wrangler`");
lines.push("(MIT OR Apache-2.0) and the `cloudflare/sandbox` shim (Apache-2.0).");
lines.push("");
lines.push("## Video tooling (not shipped)");
lines.push("");
lines.push("`video/` (the submission video's capture and composition tooling) is outside the pnpm workspace,");
lines.push("with its own `video/package.json` and lockfile, so it is not listed above. Nothing from it is");
lines.push("deployed or redistributed. It uses Remotion (`remotion`, `@remotion/*`, including");
lines.push("`@remotion/google-fonts`), which is under the Remotion licence, not an OSI licence: free for");
lines.push("individuals and companies of up to three people, a company licence otherwise. Its other");
lines.push("dependencies keep their own licence terms (see `video/package.json`).");
lines.push("");
lines.push("## Licence texts");
for (const p of pkgs) {
  lines.push("");
  lines.push(`### ${p.name} ${p.versions.join(", ")} (${p.license})`);
  lines.push("");
  const text = licenseText(p.paths);
  if (text) {
    lines.push("```text");
    lines.push(text);
    lines.push("```");
  } else {
    lines.push(`No licence file in the package; licence declared in its package.json: ${p.license}.`);
  }
}
const body = `${lines.join("\n")}\n`;

if (process.argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (cur !== body) {
    console.error("THIRD_PARTY_NOTICES.md is out of date: run node scripts/third-party-notices.mjs");
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES.md is current (${pkgs.length} packages)`);
} else {
  writeFileSync(out, body);
  console.log(`wrote THIRD_PARTY_NOTICES.md (${pkgs.length} packages)`);
}
